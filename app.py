"""
Sabaq - Voice Teaching Assistant

Two ways in:

- Upload a finished recording, transcribed in one batch request. The
  language is forced to Urdu by default: left to detect it, the batch model
  heard three of four speakers as Hindi, wrote Devanagari, kept 16% of
  technical terms in English and dropped the densest sentences. Forced to
  Urdu, the same audio kept 79% and lost none of them.
- Stream over a WebSocket, correcting each turn as it lands. The published
  evaluation uses whisper-rt, which reports the detected language per turn.
  In the deployed app, the browser microphone records a 16 kHz WAV first and
  then feeds that recording through the same streaming path; a direct hardware
  microphone remains available when Sabaq is run locally.

Either way you get:

1. A corrected transcript, with technical terms restored to English
2. A summary, key points, and practice questions
3. The Urdu vocabulary the glossary did not cover, so it can grow from
   measurements instead of guesses
4. A comparison across lectures, to show where the glossary holds and fails

Notes are generated by Gemini where possible and by Groq when Gemini is out
of quota. Model selection inside each provider is automatic, discovered with
a listing call that costs no generation quota. The sidebar can pin one
provider, which is how the two are compared on the same transcript.

Only the raw transcript is held in session state. Correction is re-run on
every render, so the fuzzy matching toggle changes the result immediately
and costs no API call.

Run:
    streamlit run app.py
"""

