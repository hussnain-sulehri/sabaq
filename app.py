def generate_notes(transcript: str) -> None:
    """
    One request per set of notes, across whichever provider answers.

    The reply shape is enforced by a schema, so a parse failure is a real
    failure and not a reason to spend three more requests on separate calls.
    """
    with st.spinner("Generating study notes..."):
        notes = study_notes(
            keys, transcript, notes_language, term_style, force=force_provider
        )

    if not notes.get("summary"):
        st.error("The model's reply could not be read. Try generating again.")
        return

    st.session_state["summary"] = notes["summary"]
    st.session_state["points"] = notes["points"]
    st.session_state["questions"] = notes["questions"]
    st.session_state["backend"] = notes.get("backend", "")


